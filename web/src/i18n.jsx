for (const [code, overrides] of Object.entries(languageOverrides)) {
  Object.assign(dictionaries[code], overrides)
}

function interpolate(value, params) {
  if (!params) return value
  return value.replace(/\{\{(\w+)\}\}/g, (_, key) => (params[key] == null ? '' : String(params[key])))
}

function normalizeLanguage(value) {
  const code = String(value || '').toLowerCase().split('-')[0]
  return LANGUAGE_CODES.has(code) ? code : 'en'
}

function detectLanguage() {
  try {
    const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY)
    if (LANGUAGE_CODES.has(stored)) return stored
  } catch {}
  const browserLanguages = navigator.languages?.length ? navigator.languages : [navigator.language]
  for (const language of browserLanguages) {
    const code = normalizeLanguage(language)
    if (LANGUAGE_CODES.has(code)) return code
  }
  return 'en'
}

const I18nContext = createContext(null)

export function I18nProvider({ children }) {
  const [language, setLanguageState] = useState(detectLanguage)

  const setLanguage = useCallback((code) => {
    const next = normalizeLanguage(code)
    setLanguageState(next)
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, next)
    } catch {}
  }, [])

  useEffect(() => {
    document.documentElement.lang = language
  }, [language])

  const value = useMemo(() => {
    const t = (key, params) => interpolate(dictionaries[language]?.[key] || dictionaries.en[key] || key, params)
    return { language, languages: LANGUAGES, setLanguage, t }
  }, [language, setLanguage])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider')
  return value
}
